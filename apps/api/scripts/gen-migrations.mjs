/**
 * Compiles `migrations/*.sql` into `src/db/migrations.generated.ts`.
 *
 * Node (Render, tests, `db:migrate`) reads the SQL files from disk. A Worker has no filesystem, so
 * `/v1/readiness` had no way to compare the checked-in migrations with `schema_migrations` and
 * reported `unreadable` / 503 for a perfectly healthy deployment. Wrangler's Text modules were
 * uploaded for this purpose but nothing imported them, and a static import would need one hand-
 * written line per migration — a missed line silently turns a pending migration into "ready".
 *
 * Generating a plain TypeScript module instead keeps a single source of truth: this script runs
 * before every Worker build/deploy, and `test/migration-manifest.test.ts` fails if the checked-in
 * copy is stale.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const migrationsDir = join(root, 'migrations');
const target = join(root, 'src', 'db', 'migrations.generated.ts');

/** Line endings must not change a checksum: migrations are authored on Windows and applied on Linux. */
export const normalizeSql = (sql) => sql.replace(/\r\n/g, '\n');

const files = (await readdir(migrationsDir))
  .filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/i.test(f))
  .sort();

if (files.length === 0) {
  throw new Error(`No migration files in ${migrationsDir}.`);
}

const entries = [];
for (const file of files) {
  const sql = await readFile(join(migrationsDir, file), 'utf8');
  const [version] = file.split('_');
  const name = file.replace(/^\d+_/, '').replace(/\.sql$/, '');
  const checksum = createHash('sha256').update(normalizeSql(sql), 'utf8').digest('hex');
  entries.push({ file, version, name, checksum, sql });
}

const body = entries
  .map(
    (e) =>
      `  {\n` +
      `    version: ${JSON.stringify(e.version)},\n` +
      `    name: ${JSON.stringify(e.name)},\n` +
      `    checksum: ${JSON.stringify(e.checksum)},\n` +
      `    sql: ${JSON.stringify(e.sql)},\n` +
      `  },`,
  )
  .join('\n');

const contents = `// Generated by scripts/gen-migrations.mjs — do not edit by hand.
// Run \`npm run gen:migrations -w @py/api\` after adding or changing a file in migrations/.
// Checksums are computed over LF-normalized text, so the same file hashes identically on Windows
// and Linux.
import type { MigrationSource } from './migration-source.ts';

export const MIGRATION_SOURCES: readonly MigrationSource[] = [
${body}
];
`;

await writeFile(target, contents, 'utf8');

console.log(
  `[gen-migrations] wrote ${relative(root, target)} (${entries.length} migrations, ${contents.length} bytes)`,
);
